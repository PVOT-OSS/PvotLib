package com.prauga.pvot.designsystem.motion

/** Shared animation durations, in milliseconds. */
public object PvotDurations {
    /** Quick state changes, such as a nav item scaling on selection. */
    public const val Short: Int = 200
    /** A nav item growing into or shrinking out of its expanded pill. */
    public const val Medium: Int = 240
    /** A list item revealing into place. */
    public const val Long: Int = 260
}
