package com.prauga.pvot.designsystem.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/** Shared spacing scale. */
public object PvotSpacing {
    /** Gaps between closely related elements. */
    public val XS: Dp = 4.dp
    /** Gaps inside a component, such as between an icon and its label. */
    public val S: Dp = 8.dp
    /** Gaps between items in a list. */
    public val M: Dp = 12.dp
    /** Padding around a screen's content. */
    public val L: Dp = 16.dp
}
